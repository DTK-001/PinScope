#!/usr/bin/env node

const fs = require("fs");
const path = require("path");

const repoRoot = path.resolve(__dirname, "..");
const defaults = {
  input: path.join(repoRoot, "data", "course-pack"),
  output: path.join(repoRoot, "src", "shared-course-defaults.js"),
  dryRun: false
};
const EARTH_RADIUS_METERS = 6371000;
const METERS_TO_YARDS = 1.0936132983;
const MIN_PLAUSIBLE_GPS_YARDAGE_RATIO = 0.45;
const MAX_PLAUSIBLE_GPS_YARDAGE_RATIO = 1.65;
const MAX_PLAUSIBLE_GPS_YARDAGE_DIFF = 250;

main().catch((error) => {
  console.error(error.message || error);
  process.exitCode = 1;
});

async function main() {
  const options = parseArgs(process.argv.slice(2));
  const loadedCourses = loadCourses(options.input);
  assertUniqueCourseIds(loadedCourses);
  const omitted = [];
  const courses = loadedCourses
    .map(sanitizeCourse)
    .filter((course) => {
      if (unusableScraperCourse(course)) {
        omitted.push(course);
        return false;
      }
      return true;
    });
  const body = [
    "// Generated by tools/build-course-pack.cjs; satellite imagery is loaded at runtime from ArcGIS.",
    `export const sharedCourseDefaults = ${JSON.stringify(courses, null, 2)};`,
    ""
  ].join("\n");

  if (options.dryRun) {
    console.log(`${courses.length} courses would be written to ${relative(options.output)}.`);
    if (omitted.length) {
      console.log(`${omitted.length} unusable scraper ${omitted.length === 1 ? "course was" : "courses were"} omitted: ${omitted.map((course) => course.name || course.id).join(", ")}.`);
    }
    return;
  }

  fs.mkdirSync(path.dirname(options.output), { recursive: true });
  fs.writeFileSync(options.output, body);
  console.log(`${courses.length} courses written to ${relative(options.output)}.`);
  if (omitted.length) {
    console.log(`${omitted.length} unusable scraper ${omitted.length === 1 ? "course was" : "courses were"} omitted: ${omitted.map((course) => course.name || course.id).join(", ")}.`);
  }
}

function assertUniqueCourseIds(courses) {
  const seen = new Set();
  const duplicates = new Set();
  courses.forEach((course) => {
    if (!course?.id) {
      return;
    }
    if (seen.has(course.id)) {
      duplicates.add(course.id);
    }
    seen.add(course.id);
  });
  if (duplicates.size) {
    throw new Error(`Duplicate course IDs in course-pack inputs: ${Array.from(duplicates).sort().join(", ")}`);
  }
}

function parseArgs(args) {
  const options = { ...defaults };
  for (let index = 0; index < args.length; index += 1) {
    const arg = args[index];
    if (arg === "--dry-run") {
      options.dryRun = true;
    } else if (arg === "--input") {
      options.input = path.resolve(repoRoot, args[++index] || "");
    } else if (arg === "--output") {
      options.output = path.resolve(repoRoot, args[++index] || "");
    } else if (arg === "--help" || arg === "-h") {
      console.log(helpText());
      process.exit(0);
    } else if (arg === "--force") {
    } else {
      throw new Error(`Unknown argument: ${arg}`);
    }
  }
  return options;
}

function helpText() {
  return `Usage: node tools/build-course-pack.cjs [--dry-run] [--input DIR] [--output FILE]

Builds src/shared-course-defaults.js from JSON files in data/course-pack/.
Satellite imagery loads at runtime from ArcGIS Location Platform Basemap
Styles sessions.`;
}

function loadCourses(inputDir) {
  if (!fs.existsSync(inputDir)) {
    return [];
  }
  return fs.readdirSync(inputDir)
    .filter((name) => name.toLowerCase().endsWith(".json"))
    .sort()
    .flatMap((name) => {
      const file = path.join(inputDir, name);
      const raw = JSON.parse(fs.readFileSync(file, "utf8"));
      if (Array.isArray(raw)) {
        return raw;
      }
      if (Array.isArray(raw.courses)) {
        return raw.courses;
      }
      return raw && typeof raw === "object" ? [raw] : [];
    });
}

function sanitizeCourse(course) {
  return sanitizePlayableCourse(stripRuntimeMetadata(stripLegacyImagery(stripLegacyAttribution(course))));
}

function stripLegacyImagery(value) {
  if (Array.isArray(value)) {
    return value.map(stripLegacyImagery);
  }
  if (!value || typeof value !== "object") {
    return value;
  }
  const legacyImageField = "snap" + "shot";
  return Object.fromEntries(
    Object.entries(value)
      .filter(([key]) => key !== legacyImageField)
      .map(([key, child]) => [key, stripLegacyImagery(child)])
  );
}

function stripLegacyAttribution(value) {
  if (Array.isArray(value)) {
    return value.map(stripLegacyAttribution);
  }
  if (!value || typeof value !== "object") {
    return typeof value === "string" ? cleanText(value) : value;
  }
  return Object.fromEntries(
    Object.entries(value).map(([key, child]) => [key, stripLegacyAttribution(child)])
  );
}

function cleanText(value) {
  const legacyProvider = "Azu" + "re Maps";
  return value.replace(new RegExp(`\\s*Imagery:\\s*${legacyProvider}\\.?`, "g"), "").trim();
}

function stripRuntimeMetadata(course) {
  if (!course || typeof course !== "object") {
    return course;
  }
  const { scraper, sources, ...next } = course;
  if (next.verification && typeof next.verification === "object") {
    const { sources: verificationSources, ...verification } = next.verification;
    next.verification = verification;
  }
  if (Array.isArray(next.holes)) {
    next.holes = next.holes.map((hole) => {
      if (!hole || typeof hole !== "object") {
        return hole;
      }
      const { sources: holeSources, ...cleanHole } = hole;
      return cleanHole;
    });
  }
  return next;
}

function sanitizePlayableCourse(course) {
  if (!course || typeof course !== "object" || !Array.isArray(course.holes)) {
    return course;
  }
  return {
    ...course,
    holes: course.holes.map(sanitizePlayableHole)
  };
}

function unusableScraperCourse(course) {
  if (course?.source !== "scraper" || !Array.isArray(course.holes) || !Array.isArray(course.tees)) {
    return false;
  }
  const holeCount = Number(course.holesCount || course.holes.length || 0);
  const maxTotalYards = Math.max(0, ...course.tees
    .map((tee) => Number(tee.totalYards))
    .filter(Number.isFinite));
  const badPars = course.holes.filter((hole) => {
    const par = Number(hole.par);
    return !Number.isFinite(par) || par < 3 || par > 5;
  }).length;
  const badYardages = course.holes.filter((hole) => {
    const yards = maxHoleYardage(hole);
    return !yards || yards < 80 || yards > 720;
  }).length;

  if (holeCount >= 18 && (maxTotalYards < 4500 || maxTotalYards > 7600)) {
    return true;
  }
  if (holeCount > 0 && badPars + badYardages >= Math.max(4, Math.ceil(holeCount / 3))) {
    return true;
  }
  return false;
}

function sanitizePlayableHole(hole) {
  if (!hole || typeof hole !== "object" || !implausibleHoleAnchors(hole)) {
    return hole;
  }
  const next = { ...hole };
  delete next.tee;
  delete next.greenCenter;
  delete next.greenFront;
  delete next.greenBack;
  if (next.geometry && typeof next.geometry === "object") {
    const { greenPolygon, holePath, tees, detection, osmGreen, osmTee, osmHole, ...geometry } = next.geometry;
    next.geometry = Object.keys(geometry).length ? geometry : undefined;
  }
  return next;
}

function implausibleHoleAnchors(hole) {
  const cardYards = maxHoleYardage(hole);
  if (!cardYards || !validGeoPoint(hole.tee) || !validGeoPoint(hole.greenCenter)) {
    return false;
  }
  const gpsYards = yardsBetween(hole.tee, hole.greenCenter);
  if (!Number.isFinite(gpsYards) || gpsYards <= 0) {
    return true;
  }
  const ratio = gpsYards / cardYards;
  const diff = Math.abs(gpsYards - cardYards);
  return ratio < MIN_PLAUSIBLE_GPS_YARDAGE_RATIO ||
    ratio > MAX_PLAUSIBLE_GPS_YARDAGE_RATIO ||
    diff > MAX_PLAUSIBLE_GPS_YARDAGE_DIFF;
}

function maxHoleYardage(hole) {
  return Math.max(0, ...Object.values(hole.yards || {})
    .map(Number)
    .filter((value) => Number.isFinite(value) && value > 0));
}

function validGeoPoint(point) {
  return Boolean(
    point &&
      Number.isFinite(Number(point.lat)) &&
      Number.isFinite(Number(point.lng)) &&
      Math.abs(Number(point.lat)) <= 90 &&
      Math.abs(Number(point.lng)) <= 180
  );
}

function yardsBetween(a, b) {
  const lat1 = Number(a.lat) * Math.PI / 180;
  const lat2 = Number(b.lat) * Math.PI / 180;
  const dLat = lat2 - lat1;
  const dLng = (Number(b.lng) - Number(a.lng)) * Math.PI / 180;
  const h = Math.sin(dLat / 2) ** 2 +
    Math.cos(lat1) * Math.cos(lat2) * Math.sin(dLng / 2) ** 2;
  return 2 * EARTH_RADIUS_METERS * Math.asin(Math.sqrt(h)) * METERS_TO_YARDS;
}

function relative(value) {
  return path.relative(repoRoot, value).replace(/\\/g, "/");
}
