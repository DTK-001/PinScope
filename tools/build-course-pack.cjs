#!/usr/bin/env node

const fs = require("node:fs");
const path = require("node:path");
const crypto = require("node:crypto");

const SNAPSHOT_WIDTH = 900;
const SNAPSHOT_HEIGHT = 1300;
const SNAPSHOT_MIN_ZOOM = 14;
const SNAPSHOT_MAX_ZOOM = 19;
const SNAPSHOT_TILE_SIZE = 512;
const SNAPSHOT_PADDING = 0.18;

const repoRoot = path.resolve(__dirname, "..");
const defaults = {
  input: path.join(repoRoot, "data", "course-pack"),
  output: path.join(repoRoot, "src", "shared-course-defaults.js"),
  snapshots: path.join(repoRoot, "assets", "snapshots"),
  force: false,
  dryRun: false
};

main().catch((error) => {
  console.error(error.message || error);
  process.exit(1);
});

async function main() {
  loadEnvFile(path.join(repoRoot, ".env.local"));
  loadEnvFile(path.join(repoRoot, ".env"));

  const options = parseArgs(process.argv.slice(2));
  const inputFiles = resolveInputFiles(options.input);
  if (!inputFiles.length) {
    throw new Error(`No JSON course inputs found at ${path.relative(repoRoot, options.input)}.`);
  }

  const azureKey = String(process.env.AZURE_MAPS_KEY || "").trim();
  const courses = inputFiles.flatMap(readInputCourses).map(normalizeCourse).filter(Boolean);
  if (!courses.length) {
    throw new Error("No usable courses were found in the input JSON.");
  }

  const summary = {
    courses: courses.length,
    holes: 0,
    generated: 0,
    reused: 0,
    skipped: 0,
    errors: []
  };

  for (const course of courses) {
    for (const hole of course.holes) {
      summary.holes += 1;
      const plan = planHoleSnapshot(hole);
      if (!plan) {
        summary.skipped += 1;
        continue;
      }

      const snapshot = await ensureSnapshot(course, hole, plan, options, azureKey, summary);
      if (snapshot) {
        hole.snapshot = snapshot;
      }
    }
  }

  const moduleText = [
    `// Generated by tools/build-course-pack.cjs on ${new Date().toISOString()}`,
    "// Edit data/course-pack/*.json, then rerun the generator instead of hand-editing this file.",
    "",
    `export const sharedCourseDefaults = ${JSON.stringify(courses, null, 2)};`,
    ""
  ].join("\n");

  if (!options.dryRun) {
    fs.mkdirSync(path.dirname(options.output), { recursive: true });
    fs.writeFileSync(options.output, moduleText);
  }

  console.log(`Course pack: ${summary.courses} course(s), ${summary.holes} hole(s).`);
  console.log(`Snapshots: ${summary.generated} generated, ${summary.reused} reused, ${summary.skipped} skipped.`);
  if (!azureKey) {
    console.log("AZURE_MAPS_KEY is not set, so missing snapshots were not downloaded.");
  }
  if (summary.errors.length) {
    console.log("Snapshot errors:");
    summary.errors.forEach((item) => console.log(`- ${item}`));
  }
  if (options.dryRun) {
    console.log("Dry run only; no files were written.");
  } else {
    console.log(`Wrote ${path.relative(repoRoot, options.output)}`);
  }
}

function parseArgs(args) {
  const options = { ...defaults };
  const positional = [];
  for (let index = 0; index < args.length; index += 1) {
    const arg = args[index];
    if (arg === "--input" || arg === "-i") {
      options.input = path.resolve(repoRoot, args[++index] || "");
    } else if (arg === "--output" || arg === "-o") {
      options.output = path.resolve(repoRoot, args[++index] || "");
    } else if (arg === "--snapshots") {
      options.snapshots = path.resolve(repoRoot, args[++index] || "");
    } else if (arg === "--force") {
      options.force = true;
    } else if (arg === "--dry-run") {
      options.dryRun = true;
    } else if (arg === "--help" || arg === "-h") {
      printHelp();
      process.exit(0);
    } else {
      positional.push(arg);
    }
  }
  if (positional.length) {
    options.input = path.resolve(repoRoot, positional[0]);
  }
  return options;
}

function printHelp() {
  console.log(`Usage:
  node tools/build-course-pack.cjs [--input data/course-pack] [--force]

Generates saved Azure satellite snapshots for every hole with confirmed tee
and greenCenter GPS coordinates. Holes missing either point are skipped.

Inputs can be:
  - one JSON course object with { id, holes }
  - an array of course objects
  - { courses: [...] }
  - { course: { id, holes } }

The script writes:
  - assets/snapshots/{courseId}/hole-XX-{fingerprint}.jpg
  - src/shared-course-defaults.js

Use --force after remapping/importing JSON to retake every confirmed snapshot.
Set AZURE_MAPS_KEY in your shell or .env.local to download missing snapshots.`);
}

function resolveInputFiles(inputPath) {
  const resolved = path.resolve(repoRoot, inputPath);
  if (!fs.existsSync(resolved)) {
    return [];
  }
  const stat = fs.statSync(resolved);
  if (stat.isFile()) {
    return resolved.endsWith(".json") ? [resolved] : [];
  }
  return fs
    .readdirSync(resolved, { withFileTypes: true })
    .flatMap((entry) => {
      const fullPath = path.join(resolved, entry.name);
      if (entry.isDirectory()) {
        return resolveInputFiles(fullPath);
      }
      return entry.isFile() && entry.name.endsWith(".json") ? [fullPath] : [];
    })
    .sort((a, b) => a.localeCompare(b));
}

function readInputCourses(file) {
  const data = JSON.parse(fs.readFileSync(file, "utf8"));
  const courses = Array.isArray(data)
    ? data
    : Array.isArray(data.courses)
      ? data.courses
      : data.course
        ? [data.course]
        : data.id && Array.isArray(data.holes)
          ? [data]
          : [];
  return courses.map((course) => ({ ...course, __sourceFile: file }));
}

function normalizeCourse(raw) {
  if (!raw || !raw.id || !Array.isArray(raw.holes)) {
    return null;
  }
  const holes = raw.holes.map(normalizeHole).filter(Boolean).sort((a, b) => a.number - b.number);
  if (!holes.length) {
    return null;
  }
  return pruneEmpty({
    id: String(raw.id),
    source: raw.source === "verified" ? "shared" : raw.source || "shared",
    homeAreaId: raw.homeAreaId || "",
    name: raw.name || String(raw.id),
    town: raw.town || "",
    postcode: raw.postcode || "",
    country: raw.country || "",
    holesCount: Number(raw.holesCount || raw.holes_count || holes.length || 18),
    par: raw.par || "",
    distanceMiles: typeof raw.distanceMiles === "number" ? raw.distanceMiles : null,
    website: raw.website || "",
    phone: raw.phone || "",
    location: normalizePoint(raw.location || { lat: raw.lat, lng: raw.lng }),
    osm: raw.osm || null,
    holesTag: raw.holesTag || "",
    attribution: raw.attribution || "OpenStreetMap contributors. Imagery: Azure Maps.",
    geometrySource: raw.geometrySource || `PinScope course pack: ${path.relative(repoRoot, raw.__sourceFile || "")}`,
    verification: raw.verification || null,
    tees: normalizeArray(raw.tees),
    holes
  });
}

function normalizeHole(raw, index) {
  if (!raw || typeof raw !== "object") {
    return null;
  }
  const number = Number(raw.number ?? raw.holeNumber ?? raw.ref ?? raw.hole ?? index + 1);
  if (!Number.isFinite(number) || number < 1) {
    return null;
  }

  const greenCenter = normalizePoint(raw.greenCenter || raw.green?.center || raw.green || raw.pin || raw.centre || raw.center);
  const teeList = normalizeTeeList(raw.tees || raw.teeBoxes || raw.tee_box || raw.teeBox);
  const tee = normalizePoint(raw.tee || teeList[0]);
  if (!tee && !greenCenter) {
    return null;
  }

  const greenPolygon = normalizePolygon(raw.greenPolygon || raw.geometry?.greenPolygon || raw.geometry?.green || raw.green?.polygon);
  const estimated = estimateGreenFrontBackFromPolygon(
    tee,
    greenCenter,
    greenPolygon,
    normalizePoint(raw.greenFront || raw.green?.front),
    normalizePoint(raw.greenBack || raw.green?.back)
  );

  return pruneEmpty({
    number,
    name: raw.name || raw.label || "",
    par: numberOrNull(raw.par),
    strokeIndex: numberOrNull(raw.strokeIndex ?? raw.si ?? raw.handicap),
    yards: normalizeYards(raw.yards),
    tee,
    greenCenter,
    greenFront: estimated.front,
    greenBack: estimated.back,
    geometry: pruneEmpty({
      ...normalizeObject(raw.geometry),
      greenPolygon,
      tees: teeList,
      detection: normalizeObject(raw.detection || raw.geometry?.detection)
    }),
    mapping: pruneEmpty({
      ...normalizeObject(raw.mapping),
      source: raw.mapping?.source || raw.source || "PinScope course pack",
      updatedAt: raw.mapping?.updatedAt || new Date().toISOString(),
      osm: raw.osm || raw.mapping?.osm || null
    }),
    osm: raw.osm || null,
    snapshot: normalizeSnapshot(raw.snapshot),
    visual: sanitizeVisualCoordinates(raw.visual)
  });
}

async function ensureSnapshot(course, hole, plan, options, azureKey, summary) {
  const geometrySignature = snapshotGeometrySignature(course, hole);
  const fingerprint = snapshotFingerprint(course, hole, plan);
  const fileName = `hole-${String(hole.number).padStart(2, "0")}-${fingerprint}.jpg`;
  const courseDir = path.join(options.snapshots, safeKeyPart(course.id));
  const filePath = path.join(courseDir, fileName);
  const imageUrl = `./${path.relative(repoRoot, filePath).replaceAll(path.sep, "/")}`;

  if (fs.existsSync(filePath) && !options.force) {
    summary.reused += 1;
    return snapshotMetadata(imageUrl, filePath, plan, fingerprint, geometrySignature);
  }

  if (!azureKey) {
    summary.skipped += 1;
    return null;
  }

  if (options.dryRun) {
    summary.generated += 1;
    return snapshotMetadata(imageUrl, filePath, plan, fingerprint, geometrySignature);
  }

  fs.mkdirSync(courseDir, { recursive: true });
  const response = await fetch(azureStaticImageUrl(plan, azureKey), {
    headers: { Accept: "image/jpeg" }
  });
  if (!response.ok) {
    const text = await response.text().catch(() => "");
    summary.errors.push(`${course.id} hole ${hole.number}: Azure snapshot failed (${response.status})${text ? ` ${text.slice(0, 140)}` : ""}`);
    summary.skipped += 1;
    return null;
  }

  fs.writeFileSync(filePath, Buffer.from(await response.arrayBuffer()));
  summary.generated += 1;
  return snapshotMetadata(imageUrl, filePath, plan, fingerprint, geometrySignature);
}

function snapshotMetadata(imageUrl, filePath, plan, fingerprint, geometrySignature) {
  return {
    imageUrl,
    storageKey: path.relative(repoRoot, filePath).replaceAll(path.sep, "/"),
    width: plan.width,
    height: plan.height,
    center: plan.center,
    zoom: plan.zoom,
    provider: "azure-maps",
    tileset: "microsoft.imagery",
    attribution: "Imagery: Azure Maps",
    generatedAt: new Date().toISOString(),
    fingerprint,
    geometrySignature
  };
}

function planHoleSnapshot(hole) {
  const points = snapshotGeoPointsForHole(hole);
  const tee = normalizePoint(hole?.tee);
  const green = normalizePoint(hole?.greenCenter || hole?.green);
  if (!tee || !green || points.length < 2) {
    return null;
  }

  let chosen = null;
  for (let zoom = SNAPSHOT_MAX_ZOOM; zoom >= SNAPSHOT_MIN_ZOOM; zoom -= 1) {
    const worldPoints = points.map((point) => geoToWorldPixel(point, zoom));
    const bounds = worldBounds(worldPoints);
    const width = bounds.maxX - bounds.minX;
    const height = bounds.maxY - bounds.minY;
    if (width <= SNAPSHOT_WIDTH * (1 - SNAPSHOT_PADDING * 2) && height <= SNAPSHOT_HEIGHT * (1 - SNAPSHOT_PADDING * 2)) {
      chosen = { zoom, bounds };
      break;
    }
  }
  if (!chosen) {
    const worldPoints = points.map((point) => geoToWorldPixel(point, SNAPSHOT_MIN_ZOOM));
    chosen = { zoom: SNAPSHOT_MIN_ZOOM, bounds: worldBounds(worldPoints) };
  }

  const centerWorld = {
    x: (chosen.bounds.minX + chosen.bounds.maxX) / 2,
    y: (chosen.bounds.minY + chosen.bounds.maxY) / 2
  };
  return {
    width: SNAPSHOT_WIDTH,
    height: SNAPSHOT_HEIGHT,
    center: worldPixelToGeo(centerWorld, chosen.zoom),
    zoom: chosen.zoom
  };
}

function snapshotGeoPointsForHole(hole) {
  const points = [
    normalizePoint(hole?.tee),
    normalizePoint(hole?.greenCenter),
    normalizePoint(hole?.greenFront),
    normalizePoint(hole?.greenBack)
  ];
  const tees = Array.isArray(hole?.geometry?.tees) ? hole.geometry.tees : [];
  tees.forEach((point) => points.push(normalizePoint(point)));
  const polygon = Array.isArray(hole?.geometry?.greenPolygon) ? hole.geometry.greenPolygon : [];
  polygon.forEach((point) => points.push(normalizePoint(point)));
  return points.filter(Boolean);
}

function estimateGreenFrontBackFromPolygon(tee, center, polygon, fallbackFront, fallbackBack) {
  if (fallbackFront || fallbackBack) {
    return {
      front: fallbackFront || center,
      back: fallbackBack || center
    };
  }
  if (!tee || !center) {
    return { front: fallbackFront || null, back: fallbackBack || null };
  }
  const localCenter = geoToLocalMeters(tee, center);
  const localPolygon = polygon.map((point) => geoToLocalMeters(tee, point));
  const targetVector = normalizeVector(localCenter);
  if (!targetVector || !localPolygon.length) {
    return {
      front: offsetAlongLine(center, tee, 10),
      back: offsetAlongLine(center, tee, -10)
    };
  }
  let front = null;
  let back = null;
  localPolygon.forEach((point, index) => {
    const projection = point.x * targetVector.x + point.y * targetVector.y;
    if (!front || projection < front.projection) {
      front = { projection, point: polygon[index] };
    }
    if (!back || projection > back.projection) {
      back = { projection, point: polygon[index] };
    }
  });
  return {
    front: front?.point || offsetAlongLine(center, tee, 10),
    back: back?.point || offsetAlongLine(center, tee, -10)
  };
}

function offsetAlongLine(center, toward, meters) {
  const local = geoToLocalMeters(center, toward);
  const vector = normalizeVector(local);
  if (!vector) {
    return center;
  }
  return localMetersToGeo(center, { x: vector.x * meters, y: vector.y * meters });
}

function geoToLocalMeters(origin, point) {
  const latScale = 111320;
  const lngScale = 111320 * Math.cos((Number(origin.lat) * Math.PI) / 180);
  return {
    x: (Number(point.lng) - Number(origin.lng)) * lngScale,
    y: (Number(point.lat) - Number(origin.lat)) * latScale
  };
}

function localMetersToGeo(origin, point) {
  const latScale = 111320;
  const lngScale = 111320 * Math.cos((Number(origin.lat) * Math.PI) / 180);
  return roundPoint({
    lat: Number(origin.lat) + point.y / latScale,
    lng: Number(origin.lng) + point.x / lngScale
  });
}

function normalizeVector(vector) {
  const length = Math.hypot(Number(vector.x), Number(vector.y));
  if (!Number.isFinite(length) || length <= 0) {
    return null;
  }
  return { x: Number(vector.x) / length, y: Number(vector.y) / length };
}

function azureStaticImageUrl(plan, key) {
  const params = new URLSearchParams({
    "api-version": "2024-04-01",
    tilesetId: "microsoft.imagery",
    center: `${plan.center.lng},${plan.center.lat}`,
    zoom: String(plan.zoom),
    width: String(plan.width),
    height: String(plan.height),
    format: "jpeg",
    view: "Auto",
    "subscription-key": key
  });
  return `https://atlas.microsoft.com/map/static?${params.toString()}`;
}

function snapshotFingerprint(course, hole, plan) {
  return crypto
    .createHash("sha256")
    .update(JSON.stringify({
      course: course.id,
      hole: hole.number,
      tee: normalizePoint(hole.tee),
      green: normalizePoint(hole.greenCenter),
      front: normalizePoint(hole.greenFront),
      back: normalizePoint(hole.greenBack),
      polygon: Array.isArray(hole?.geometry?.greenPolygon) ? hole.geometry.greenPolygon.map(normalizePoint).filter(Boolean) : [],
      plan
    }))
    .digest("hex")
    .slice(0, 10);
}

function snapshotGeometrySignature(course, hole) {
  return fnv1a(JSON.stringify({
    course: course.id,
    hole: Number(hole.number),
    tee: normalizePoint(hole.tee),
    green: normalizePoint(hole.greenCenter),
    front: normalizePoint(hole.greenFront),
    back: normalizePoint(hole.greenBack),
    polygon: Array.isArray(hole?.geometry?.greenPolygon) ? hole.geometry.greenPolygon.map(normalizePoint).filter(Boolean) : []
  })).toString(16).padStart(8, "0");
}

function fnv1a(value) {
  let hash = 0x811c9dc5;
  for (let index = 0; index < value.length; index += 1) {
    hash ^= value.charCodeAt(index);
    hash = Math.imul(hash, 0x01000193) >>> 0;
  }
  return hash >>> 0;
}

function worldBounds(points) {
  return {
    minX: Math.min(...points.map((point) => point.x)),
    maxX: Math.max(...points.map((point) => point.x)),
    minY: Math.min(...points.map((point) => point.y)),
    maxY: Math.max(...points.map((point) => point.y))
  };
}

function geoToWorldPixel(position, zoom) {
  const lat = Math.max(-85.05112878, Math.min(85.05112878, Number(position.lat)));
  const lng = Number(position.lng);
  const scale = SNAPSHOT_TILE_SIZE * 2 ** zoom;
  const sinLat = Math.sin((lat * Math.PI) / 180);
  return {
    x: ((lng + 180) / 360) * scale,
    y: (0.5 - Math.log((1 + sinLat) / (1 - sinLat)) / (4 * Math.PI)) * scale
  };
}

function worldPixelToGeo(pixel, zoom) {
  const scale = SNAPSHOT_TILE_SIZE * 2 ** zoom;
  const lng = (pixel.x / scale) * 360 - 180;
  const n = Math.PI - (2 * Math.PI * pixel.y) / scale;
  const lat = (180 / Math.PI) * Math.atan(Math.sinh(n));
  return roundPoint({ lat, lng });
}

function normalizeTeeList(value) {
  const list = Array.isArray(value) ? value : value ? [value] : [];
  return list.map((item, index) => {
    const point = normalizePoint(item);
    if (!point) {
      return null;
    }
    return pruneEmpty({
      name: item?.name || item?.colour || item?.color || `Tee ${index + 1}`,
      ...point,
      yards: numberOrNull(item?.yards),
      osm: item?.osm || null
    });
  }).filter(Boolean);
}

function normalizePoint(value) {
  if (!value) {
    return null;
  }
  if (Array.isArray(value) && value.length >= 2) {
    const a = Number(value[0]);
    const b = Number(value[1]);
    if (Number.isFinite(a) && Number.isFinite(b)) {
      if (Math.abs(a) <= 90 && Math.abs(b) <= 180) {
        return roundPoint({ lat: a, lng: b });
      }
      if (Math.abs(b) <= 90 && Math.abs(a) <= 180) {
        return roundPoint({ lat: b, lng: a });
      }
    }
    return null;
  }
  const lat = Number(value.lat ?? value.latitude);
  const lng = Number(value.lng ?? value.lon ?? value.longitude);
  if (!Number.isFinite(lat) || !Number.isFinite(lng) || Math.abs(lat) > 90 || Math.abs(lng) > 180) {
    return null;
  }
  return roundPoint({ lat, lng });
}

function normalizePolygon(value) {
  const list = Array.isArray(value) ? value : [];
  return list.map(normalizePoint).filter(Boolean);
}

function normalizeArray(value) {
  const list = Array.isArray(value) ? value : [];
  return list.map((item) => {
    if (normalizePoint(item)) {
      return { ...item, ...normalizePoint(item) };
    }
    return item && typeof item === "object" ? pruneEmpty({ ...item }) : item;
  }).filter((item) => item !== null && item !== undefined && item !== "");
}

function normalizeObject(value) {
  return value && typeof value === "object" && !Array.isArray(value) ? pruneEmpty({ ...value }) : null;
}

function normalizeYards(value) {
  if (Number.isFinite(Number(value))) {
    return { white: Math.round(Number(value)) };
  }
  return normalizeObject(value);
}

function normalizeSnapshot(snapshot) {
  if (!snapshot || typeof snapshot !== "object") {
    return null;
  }
  const imageUrl = String(snapshot.imageUrl || snapshot.url || "").trim();
  const center = normalizePoint(snapshot.center);
  const zoom = Number(snapshot.zoom);
  const width = Number(snapshot.width);
  const height = Number(snapshot.height);
  if (!imageUrl || !center || !Number.isFinite(zoom) || !Number.isFinite(width) || !Number.isFinite(height) || width <= 0 || height <= 0) {
    return null;
  }
  return pruneEmpty({
    ...snapshot,
    imageUrl,
    center,
    zoom,
    width,
    height
  });
}

function sanitizeVisualCoordinates(visual) {
  if (!visual || typeof visual !== "object") {
    return visual;
  }
  const next = { ...visual };
  if (!isPercentPair(next.tee)) {
    delete next.tee;
  }
  if (!isPercentPair(next.green)) {
    delete next.green;
  }
  return pruneEmpty(next);
}

function isPercentPair(value) {
  return Array.isArray(value) && value.length >= 2 && Number.isFinite(Number(value[0])) && Number.isFinite(Number(value[1]));
}

function numberOrNull(value) {
  const number = Number(value);
  return Number.isFinite(number) ? number : null;
}

function roundPoint(point) {
  return { lat: Number(Number(point.lat).toFixed(6)), lng: Number(Number(point.lng).toFixed(6)) };
}

function pruneEmpty(value) {
  if (!value || typeof value !== "object" || Array.isArray(value)) {
    return value;
  }
  const next = {};
  Object.entries(value).forEach(([key, item]) => {
    if (item === null || item === undefined || item === "") {
      return;
    }
    if (Array.isArray(item) && !item.length) {
      return;
    }
    if (item && typeof item === "object" && !Array.isArray(item) && !Object.keys(item).length) {
      return;
    }
    next[key] = item;
  });
  return next;
}

function safeKeyPart(value) {
  return String(value || "course").toLowerCase().replace(/[^a-z0-9_-]+/g, "-").replace(/^-+|-+$/g, "") || "course";
}

function loadEnvFile(file) {
  if (!fs.existsSync(file)) {
    return;
  }
  fs.readFileSync(file, "utf8").split(/\r?\n/).forEach((line) => {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) {
      return;
    }
    const separator = trimmed.indexOf("=");
    if (separator <= 0) {
      return;
    }
    const name = trimmed.slice(0, separator).trim();
    const value = trimmed.slice(separator + 1).trim().replace(/^['"]|['"]$/g, "");
    if (name && !process.env[name]) {
      process.env[name] = value;
    }
  });
}
